def password_hash(password):
    salt = secrets.token_bytes(16)
    digest = hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), salt, PASSWORD_ITERATIONS)
    return f"pbkdf2_sha256${PASSWORD_ITERATIONS}${salt.hex()}${digest.hex()}"

def is_password_hash(encoded):
    return encoded.startswith("pbkdf2_sha256$")

def verify_password(password, encoded):
    if not is_password_hash(encoded):
        return hmac.compare_digest(password.encode("utf-8"), encoded.encode("utf-8"))
    try:
        algorithm, iterations, salt, expected = encoded.split("$")
        iterations = int(iterations)
        if algorithm != "pbkdf2_sha256" or not 1 <= iterations <= 1_000_000:
            return False
        if len(bytes.fromhex(salt)) < 16 or len(expected) != 64:
            return False
        digest = hashlib.pbkdf2_hmac("sha256", password.encode("utf-8"), bytes.fromhex(salt), iterations)
    except (ValueError, TypeError):
        return False
    return hmac.compare_digest(digest.hex(), expected)

def authenticate_user(username, password):
    normalized_username = username.strip().casefold()
    with USER_FILE_LOCK:
        users = read_users()
        user = next((u for u in users if u.get("password_hash")
                     and u["username"].casefold() == normalized_username), None)
        if not user or not verify_password(password, user["password_hash"]):
            return None
        if not is_password_hash(user["password_hash"]):
            user["password_hash"] = password_hash(password)
            user["created_on"] = dt.date.today().isoformat()
            write_users(users)
        return user

def read_users():
    if not USER_FILE.exists():
        return []
    with USER_FILE.open(newline="", encoding="utf-8") as f:
        users = list(csv.DictReader(f))
    required = {"username", "password_hash", "role", "created_on"}
    if users and not required.issubset(users[0]):
        raise ValueError("users_information.csv must contain username, password_hash, role, and created_on columns.")
    if any(not user.get("username") or user.get("role") not in ROLES
           or (user.get("password_hash") and not user.get("created_on")) for user in users):
        raise ValueError("users_information.csv contains an invalid account or unsupported role.")
    return users

def write_users(users):
    fields = ["username", "password_hash", "role", "created_on"]
    with USER_FILE_LOCK:
        with NamedTemporaryFile("w", newline="", encoding="utf-8", dir=USER_FILE.parent, delete=False) as f:
            temp_path = Path(f.name)
            writer = csv.DictWriter(f, fieldnames=fields)
            writer.writeheader()
            writer.writerows(users)
        try:
            os.chmod(temp_path, 0o600)
            os.replace(temp_path, USER_FILE)
        finally:
            temp_path.unlink(missing_ok=True)

def create_user_account(username, password, role):
    normalized_username = username.strip().casefold()
    if not normalized_username:
        raise ValueError("Username is required.")
    if len(password) < 12:
        raise ValueError("Use a password of at least 12 characters.")
    if role not in ROLES:
        raise ValueError("Choose a supported role.")
    with USER_FILE_LOCK:
        users = read_users()
        existing = next((user for user in users if user["username"].casefold() == normalized_username), None)
        if existing:
            if existing.get("password_hash"):
                raise ValueError("That username already has an active account.")
            if existing["role"] != role:
                raise ValueError("Use the role assigned to this pending account.")
            existing["password_hash"] = password_hash(password)
            existing["created_on"] = dt.date.today().isoformat()
        else:
            users.append({
                "username": normalized_username,
                "password_hash": password_hash(password),
                "role": role,
                "created_on": dt.date.today().isoformat(),
            })
        write_users(users)
    return normalized_username

