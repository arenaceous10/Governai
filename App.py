TEXT_STARTS = ("how", "what", "which", "who", "when", "where", "describe", "list")      # these get a text box
CHOICE_STARTS = ("is", "are", "does", "do", "can", "will", "has", "have")               # these get Yes / No / Not answered

def wording_kind(text):
    """'text' or 'yn' from the first word of the question, or None when the first word is on neither list."""
    m = re.match(r"[^A-Za-z]*([A-Za-z]+)", str(text or ""))
    w = m.group(1).lower() if m else ""
    return "text" if w in TEXT_STARTS else "yn" if w in CHOICE_STARTS else None

def question_kind(text, declared=None):
    """The input a question gets. A safeguard (maturity) question keeps its own scale. Otherwise the wording decides; the type
    Gemini returned is used only when the wording is on neither list, and a missing type then means a text box."""
    d = str(declared or "").strip().lower()
    if d.startswith("m"):
        return "mat"
    return wording_kind(text) or ("yn" if d.startswith("y") else "text")

def parse_questions(raw, limit):
    """Turn Gemini's JSON items into ([(question, kind)], {question: tags}). Nothing from the model is trusted:
    a bad dimension or a bad risky_answer leaves the question untagged, and only the first 3 critical flags count."""
    out, meta, crit, untagged = [], {}, 0, 0
    try: st.session_state["qmeta_untagged"] = 0
    except Exception: pass
    for q in raw:
        if len(out) >= limit:
            break
        if not (isinstance(q, dict) and str(q.get("q", "")).strip()):
            continue
        text = str(q["q"]).strip()
        if text in [x[0] for x in out]:
            continue
        kind = question_kind(text, q.get("type"))      # mat = safeguard maturity question
        out.append((text, kind))
        dim = q.get("dimension")
        if dim not in DIMS:
            untagged += 1
            continue
        tags = dict(dimension=dim, why=str(q.get("why", "")).strip()[:200], risky=None, critical=False, safeguard=(kind == "mat"))
        if kind == "yn":
            risky = str(q.get("risky_answer", "")).strip().lower()
            if risky not in ("yes", "no"):
                untagged += 1
                continue
            tags["risky"] = risky
            if q.get("critical") is True and crit < 3:
                tags["critical"] = True; crit += 1
        meta[text] = tags
    try: st.session_state["qmeta_untagged"] = untagged
    except Exception: pass
    return out, meta

