def secret(name, default=""):
    try:
        return st.secrets.get(name, default)
    except Exception:
        return default

@st.cache_resource
def _pg_pool():
    import psycopg2
    return psycopg2.connect(secret("DATABASE_URL"), connect_timeout=10)

def db():
    url = secret("DATABASE_URL")
    if url:
        raw = _pg_pool()
        try:
            raw.cursor().execute("select 1")
        except Exception:
            try: raw.rollback()
            except Exception: pass
            _pg_pool.clear(); raw = _pg_pool()
        return Conn(raw, True)
    c = sqlite3.connect(DB, check_same_thread=False)
    c.row_factory = sqlite3.Row
    return Conn(c, False)

def qdf(c, sql, params=()):
    cur = c.execute(sql, params)
    return pd.DataFrame([dict(r) for r in cur.fetchall()], columns=cur.cols)

