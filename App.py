UPSERT_KEYS = {"approvals": "(uc,stage,role)", "checklist": "(uc,stage,item)"}

class Row(dict):
    """dict that also supports row[0] like sqlite3.Row"""
    def __getitem__(self, k):
        if isinstance(k, (int, slice)):
            return list(self.values())[k]
        return dict.__getitem__(self, k)

class Cur:
    def __init__(self, rows, lastrowid=None, cols=None):
        self._rows = rows; self.lastrowid = lastrowid; self.cols = cols or []
    def fetchone(self): return self._rows[0] if self._rows else None
    def fetchall(self): return list(self._rows)
    def __iter__(self): return iter(self._rows)

class Conn:
    def __init__(self, raw, pg):
        self.raw = raw; self.pg = pg
    def _sql(self, sql):
        if not self.pg: return sql
        m = _re.match(r"\s*insert or replace into (\w+)\s+values\s*\((.*)\)\s*$", sql, _re.S | _re.I)
        if m:
            t, vals = m.group(1), m.group(2)
            cols = {"approvals": ["uc","stage","role","outcome","comment","at"],
                    "checklist": ["uc","stage","item","done"]}[t]
            key = [x.strip() for x in UPSERT_KEYS[t].strip("()").split(",")]
            upd = ", ".join(f"{x}=excluded.{x}" for x in cols if x not in key)
            sql = f"insert into {t}({','.join(cols)}) values({vals}) on conflict {UPSERT_KEYS[t]} do update set {upd}"
        return sql.replace("?", "%s")
    def execute(self, sql, params=()):
        sql2 = self._sql(sql)
        if self.pg:
            cur = self.raw.cursor()
            want_id = _re.match(r"\s*insert into use_cases", sql2, _re.I) is not None
            if want_id: sql2 += " returning id"
            try:
                cur.execute(sql2, tuple(params))
            except Exception:
                self.raw.rollback(); raise
            rows, lid, names = [], None, []
            if cur.description:
                names = [d[0] for d in cur.description]
                rows = [Row(zip(names, r)) for r in cur.fetchall()]
            if want_id and rows: lid = rows[0]["id"]
            return Cur(rows, lid, names)
        cur = self.raw.execute(sql2, tuple(params))
        names = [d[0] for d in cur.description] if cur.description else []
        rows = [Row(dict(r)) for r in cur.fetchall()] if cur.description else []
        return Cur(rows, cur.lastrowid, names)
    def commit(self):
        self.raw.commit()
    def close(self):
        try: self.raw.close()
        except Exception: pass

