# ---------- answers -> minimum risk scores (fixed rules, no AI) ----------
def answer_floors(qs, answers, meta):
    """Floors from yes/no answers only. A risky answer gives floor 2 (3 if the question is critical). A critical question
    left unanswered gives floor 2. One entry per dimension: the highest floor wins. Text answers never give a floor."""
    best = {}
    for q, kind in qs:
        m = meta.get(q)
        if kind != "yn" or not m or m.get("dimension") not in DIMS or m.get("risky") not in ("yes", "no"):
            continue
        a = str(answers.get(q, "")).strip()
        if a in ("", "Not answered"):
            if not m.get("critical"):
                continue            # already counted and flagged as unanswered
            floor, unanswered = 2, True
        elif a.lower() == m["risky"]:
            floor, unanswered = (3 if m.get("critical") else 2), False
        else:
            continue
        d = m["dimension"]
        if d not in best or floor > best[d]["floor"]:
            best[d] = dict(dimension=d, floor=floor, question=q, answer=a, unanswered=unanswered)
    return list(best.values())

def apply_floors(scores, floors):
    """Returns (effective scores, [(dimension, old, new, floor entry)]). A floor can only raise a score."""
    eff, raised = dict(scores), []
    for f in floors or []:
        d = f.get("dimension")
        try: fl = int(f.get("floor"))
        except (TypeError, ValueError): continue
        if d in eff and 1 <= fl <= 3 and fl > eff[d]:
            raised.append((d, eff[d], fl, f)); eff[d] = fl
    return eff, raised

AUTOMATION_FLOOR = {"advisory": 1, "human-in-loop": 2, "fully automated": 3}

def with_dropdown_floor(floors, auto):
    """Adds the Degree of automation dropdown as a floor on Automation. Same rule as an answer floor: the highest wins,
    and it can only raise the slider."""
    fl = AUTOMATION_FLOOR.get(auto)
    if not fl:
        return list(floors)
    entry = dict(dimension="Automation", floor=fl, question=f"Degree of automation: {auto}", answer=auto, source="dropdown")
    out, placed = [], False
    for f in floors:
        if f.get("dimension") == "Automation":
            out.append(entry if fl > f["floor"] else f); placed = True
        else:
            out.append(f)
    return out if placed else out + [entry]

def consistency_notes(auto, qs, answers, meta):
    """Code only, no AI. If the dropdown says fully automated but an Automation-tagged yes/no question was answered with
    the non-risky answer (a human reviews every case), say so. Never changes a score."""
    if auto != "fully automated":
        return []
    notes = []
    for q, kind in qs:
        m = meta.get(q)
        a = str(answers.get(q, "")).strip().lower()
        if kind == "yn" and m and m.get("dimension") == "Automation" and m.get("risky") in ("yes", "no") \
                and a in ("yes", "no") and a != m["risky"]:
            notes.append(f"Degree of automation is fully automated, but an answer says a human reviews every case: {q}")
    return notes

