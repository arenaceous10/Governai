def reassess_items(c, u):
    """(reason, date of the event or None) for every current reason a system may need re-scoring."""
    risk, intake, out = json.loads(u["risk"]), json.loads(u["intake"]), []
    ch = c.execute("select at from changes where uc=? and material=1 order by at desc", (u["id"],)).fetchone()
    if ch:
        out.append((f"A material change was requested on {ch['at']}", ch["at"]))
    sev = c.execute("select title, at from incidents where uc=? and status='open' and severity in ('high','critical') order by at desc", (u["id"],)).fetchall()
    for i in sev:
        out.append((f"Open high or critical incident: {i['title']}", i["at"]))
    if sev:     # an open severe incident counts as charter trigger 8
        out.append((f"Counts as an escalation trigger: {TRIG_UNRESOLVED}", sev[0]["at"]))
    if u["status"] == "production" and u["next_review"] and u["next_review"] < dt.date.today().isoformat():
        out.append((f"Periodic review overdue since {u['next_review']}", u["next_review"]))
    new = [g for g in intake.get("geos", []) if risk.get("registered_geos") is not None and g not in risk["registered_geos"]]
    if new:
        out.append(("New jurisdiction added: " + ", ".join(new), None))
    return out

def reassess_reasons(c, u):
    """Why a system may need re-scoring. A flag only: it never changes the tier or blocks anything."""
    return [r for r, _ in reassess_items(c, u)]

def last_rescore(c, uid):
    return c.execute("select at from rescores where uc=? order by id desc limit 1", (uid,)).fetchone()

def reassess_status(c, u):
    """active: reasons that arose since the last re-score (the flag). context: reasons still on record but already
    covered by a re-score. rescored_on: date of the last re-score, or None."""
    items, last = reassess_items(c, u), last_rescore(c, u["id"])
    at = last["at"] if last else None
    active = [r for r, ev in items if at is None or (ev is not None and str(ev) > at)]
    return dict(active=active, context=[r for r, _ in items if r not in active], rescored_on=at[:10] if at else None, any=bool(items))

def rescore_use_case(c, u, new_intake, proh, trig, scores, actor):
    """Re-runs the same assessment as registration with changed answers. The old answers are kept in `rescores`.
    Stage, status and approvals are not touched: a re-score alone is not a material change. Returns (old tier, new tier, reasons)."""
    old_intake, old_risk = json.loads(u["intake"]), json.loads(u["risk"])
    trig = list(trig)
    if c.execute("select 1 from incidents where uc=? and status='open' and severity in ('high','critical')", (u["id"],)).fetchone() and TRIG_UNRESOLVED not in trig:
        trig.append(TRIG_UNRESOLVED)
    tier, total, reasons, risk = assess(new_intake, proh, trig, scores)
    c.execute("insert into rescores(uc,at,actor,old_tier,new_tier,snapshot) values(?,?,?,?,?,?)",
              (u["id"], now(), actor, u["tier"], tier, json.dumps(dict(intake=old_intake, risk=old_risk))))
    c.execute("update use_cases set tier=?, risk=?, intake=? where id=?", (tier, json.dumps(risk), json.dumps(new_intake), u["id"]))
    c.commit()
    log(actor, "rescored", u["id"], f"tier {u['tier']} -> {tier}")
    return u["tier"], tier, reasons

