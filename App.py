def tier_breakdown(u):
    """Legal class, inherent tier, residual tier and final tier for the detail page and report. None for systems that
    were registered before charter tiering (shown as 'not assessed')."""
    risk = json.loads(u["risk"])
    if not risk.get("assessed"):
        return None
    lab = lambda t: TIER_LABEL.get(t, str(t).upper())
    legal = risk.get("legal_class")
    rows = [("Legal class", legal or "Not assessed"),
            ("Inherent tier (before safeguards)", f"{lab(risk['inherent_tier'])} ({risk['inherent_score']}/100)"),
            ("Residual tier (after safeguards)", f"{lab(risk['residual_tier'])} ({risk['residual_score']}/100)"),
            ("Final tier", lab(risk["final_tier"]))]
    res = risk["residual_tier"]
    if res == "prohibited":
        why = "A prohibited practice drove the final tier."
    elif legal and TIER_RANK[LEGAL_TIER[legal]] > TIER_RANK[res]:
        why = "The legal class drove the final tier."
    elif res != band(risk["residual_score"]):
        why = "A trigger or a critical rating drove the final tier."
    else:
        why = "The residual risk score drove the final tier."
    return rows, why

