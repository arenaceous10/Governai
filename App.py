def is_yes_no_question(question):
    text = question.strip()
    if not _re.match(r"^(can|could|do|does|did|is|are|was|were|has|have|had|will|would|should)\b", text, _re.I):
        return False
    return not _re.search(r",\s*(?:and|or)\s+(?:who|what|where|when|why|how|can|could|do|does|is|are|has|have|will|would|should)\b", text, _re.I)

