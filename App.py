def _band_ranges(bands):
    """'MINIMAL (low) 0 to 29, ...' from the stored bands (upper bound exclusive), or None when none were stored."""
    if not bands:
        return None
    out, lo = [], 0
    for upper, t in bands:
        out.append(f"{TIER_LABEL.get(t, str(t).upper())} ({t}) {lo} to {min(int(upper) - 1, 100)}")
        lo = int(upper)
    return ", ".join(out)

def tier_steps(u):
    """The tier calculation as [(heading, [lines])]. Every number is read from the risk record that assess() wrote when it
    computed the tier, so this can never disagree with the result. A field an older system lacks reads 'not recorded'."""
    risk = json.loads(u["risk"])
    lab = lambda t: TIER_LABEL.get(t, str(t).upper()) if t else NOT_RECORDED
    scores = risk.get("scores") if isinstance(risk.get("scores"), dict) else None
    res = risk.get("residual_scores") if isinstance(risk.get("residual_scores"), dict) else None
    inh, inh_tier = risk.get("inherent_score"), risk.get("inherent_tier")
    bands = risk.get("bands")
    steps = []
    # 1. scores and total
    l1 = [f"{d}: {scores[d]} (weight {WEIGHTS[d]})" if scores and d in scores else f"{d}: {NOT_RECORDED}" for d in DIMS]
    sub = risk.get("submitted_scores")
    if scores and isinstance(sub, dict):
        up = [f"{d} {sub[d]} to {scores[d]}" for d in DIMS if d in sub and d in scores and sub[d] != scores[d]]
        if up:
            l1.append("Raised from the ratings entered, by answers: " + ", ".join(up))
    if inh is not None:
        l1.append(f"Total: {inh}/100 (each score is weighted, then scaled so that all 1s is 0 and all 3s is 100)")
    else:
        l1.append(f"Total before safeguards: {NOT_RECORDED}" + (f". Score on record: {risk['total']}/100" if risk.get("total") is not None else ""))
    steps.append(("1. Dimension scores and total", l1))
    # 2. inherent tier
    band_i = risk.get("inherent_band")
    l2 = ["Score bands: " + (_band_ranges(bands) or NOT_RECORDED)]
    if inh is not None and band_i:
        l2.append(f"The total {inh} falls in the {lab(band_i)} ({band_i}) band.")
    else:
        l2.append(f"Band for the total: {NOT_RECORDED}")
    raised = bool(inh_tier and band_i and inh_tier != band_i and not risk.get("prohibited"))
    l2.append(f"Inherent tier: {lab(inh_tier)}" + (" (the floors in step 3 raised it above the band)" if raised else ""))
    steps.append(("2. Inherent tier (before safeguards)", l2))
    # 3. triggers and floors
    fired = risk.get("triggers_fired")
    l3 = []
    if fired is None:
        l3.append(f"Escalation triggers: {NOT_RECORDED}")
    elif fired:
        l3 += [f"Fired: {canon_trigger(t)}" for t in fired]
        if band_i in ("low", "medium"):
            l3.append(f"A trigger forces HIGH. By score alone this would be {lab(band_i)}.")
        elif band_i:
            l3.append("A trigger forces HIGH, but the score already puts it in High, so nothing changes.")
        else:
            l3.append("A trigger forces HIGH.")
    else:
        l3.append("No escalation trigger fired, so no trigger forces High.")
    crit = risk.get("critical_at_3")
    if crit is None and scores:
        crit = [d for d in CRITICAL if scores.get(d) == 3]
    if crit is not None:
        l3.append(f"{len(crit)} of the {len(CRITICAL)} critical dimensions ({', '.join(CRITICAL)}) are rated 3: {', '.join(crit) or 'none'}. "
                  + ("Three or more forces HIGH." if len(crit) >= 3 else "Three or more would force HIGH, so this does not."))
    if risk.get("prohibited"):
        l3.append("Prohibited practice: " + "; ".join(risk["prohibited"]) + ". The final tier is UNACCEPTABLE whatever the score.")
    steps.append(("3. Escalation triggers that force High", l3))
    # 4. safeguard credit
    l4 = []
    if scores and res:
        for d in DIMS:
            if d in scores and d in res:
                l4.append(f"{d}: lowered by {scores[d] - res[d]} ({scores[d]} to {res[d]})" if scores[d] != res[d] else f"{d}: no credit")
    else:
        l4.append(f"Credit per dimension: {NOT_RECORDED}")
    l4.append(f"Limits: at most {MAX_STEPS_PER_DIM} steps per dimension, {PROTECTED_MAX_STEPS} for {' and '.join(PROTECTED_DIMS)}, and a dimension never drops below 1.")
    pinned = risk.get("pinned_dims")
    if pinned is None:     # older system: work it out from the triggers it fired
        pinned = {}
        for trig_, dims_ in trigger_pins(risk.get("triggers_fired", [])).items():
            for d in dims_:
                pinned.setdefault(d, []).append(f"trigger: {trig_}")
    held = {h.get("dimension"): h for h in risk.get("held_credits") or []}
    for d, why in pinned.items():
        if d in held:
            offered = f" A credit was offered ({held[d].get('question')}, {held[d].get('level')}) and was not given."
        else:
            offered = " No credit was offered." if risk.get("held_credits") is not None else ""
        at = f" at {scores[d]}" if scores and d in scores else ""
        l4.append(f"Held back: {d}{at} gets no credit because of {'; '.join(why)}.{offered}")
    if not pinned:
        l4.append("No dimension was held back from credit.")
    steps.append(("4. Safeguard credit", l4))
    # 5. residual tier
    res_s, res_t, band_r = risk.get("residual_score"), risk.get("residual_tier"), risk.get("residual_band")
    l5 = []
    if res_s is not None and res_t:
        l5.append(f"After credit the total is {res_s}/100 ({lab(band_r)} band). Residual tier: {lab(res_t)}.")
        if inh is None or inh_tier is None:
            sentence = f"The inherent tier is {NOT_RECORDED}, so the step from inherent to residual cannot be shown."
        else:
            gave = inh - res_s
            pts = f"{gave} point{'s' if gave != 1 else ''}"
            if gave <= 0:
                sentence = f"No safeguard credit was given, so the residual tier ({lab(res_t)}) is the same as the inherent tier ({lab(inh_tier)})."
            elif res_t != inh_tier:
                sentence = f"Safeguard credit took {pts} off the total ({inh} to {res_s}), which moved the tier from {lab(inh_tier)} to {lab(res_t)}."
            else:
                sentence = (f"Safeguard credit took {pts} off the total ({inh} to {res_s}), but the tier stays {lab(inh_tier)}"
                            + (", because a trigger or critical rating keeps it there." if band_r and band_r != res_t else "."))
        l5.append(sentence)
    else:
        l5.append(f"Residual tier: {NOT_RECORDED}")
    steps.append(("5. Residual tier (after safeguards)", l5))
    # 6. legal class and plain meanings
    legal = risk.get("legal_class")
    l6 = []
    if legal:
        l6.append(f"Legal class: {legal}" + (f" ({risk['legal_reason']})" if risk.get("legal_reason") else ""))
        l6.append("Meaning: " + LEGAL_MEANING.get(legal, NOT_RECORDED))
    else:
        l6.append(f"Legal class: {NOT_RECORDED} (this system was registered before legal class was recorded)")
    l6.append(f"Final tier: {lab(risk.get('final_tier') or u['tier'])}, the stricter of the residual tier and the legal class.")
    l6.append("Inherent tier: the risk before any safeguard is counted.")
    l6.append("Residual tier: the risk that is left after credit for safeguards that are in place or tested.")
    l6.append("Legal class: a fixed rule on the domain and use, independent of the score. It sets the lowest final tier the system can have.")
    steps.append(("6. Legal class and what it means", l6))
    return steps

