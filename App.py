def retrieve(query, laws, k=12):
    docs = [r for r in REGS if r[0] in laws]
    if not docs: return []
    texts = [f"{a} {b} {t}" for a, b, t in docs]
    vec = TfidfVectorizer(stop_words="english").fit(texts + [query])
    sims = cosine_similarity(vec.transform([query]), vec.transform(texts))[0]
    ranked = sorted(zip(sims, range(len(docs))), reverse=True)[:k]
    return [(round(float(s), 3), docs[i]) for s, i in ranked if s > 0]

def gemini_models():
    """Models to try, in order: GEMINI_MODEL, then GEMINI_FALLBACK_MODELS (comma separated) or the default fallbacks."""
    main = str(secret("GEMINI_MODEL", "gemini-3.8-flash") or "gemini-3.8-flash")
    fb = str(secret("GEMINI_FALLBACK_MODELS", "") or "")
    rest = fb.split(",") if fb.strip() else ["gemini-3.1-flash-lite", "gemini-flash-lite-latest", "gemini-3.5-flash-lite"]
    out = []
    for m in [main] + rest:
        m = m.strip()
        if m and m not in out:
            out.append(m)
    return out

def gemini_call(key, body, max_models=None):
    """POST to Gemini, trying each model in turn. The first model gets 2 attempts (2s apart), each fallback 1, on
    HTTP 429/503, timeout or connection error, then on to the next model. HTTP 404 moves on at once (the model may
    be retired). A 400 that mentions thinking is retried once on the same model without thinkingConfig. Any other
    error (400, 403 ...) stops straight away, because another model will not fix it.
    Returns (response_json, None, model_used) on success or (None, message, None) on failure. The key goes in a
    header, so it never appears in a URL, an exception or the message."""
    failed = []                       # (model, outcome) for each model that did not answer
    for idx, model in enumerate(gemini_models()[:max_models]):    # max_models=None tries every model
        url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent"
        think = model.startswith("gemini-3")    # thinkingConfig is only sent to Gemini 3 models
        tries = 2 if idx == 0 else 1
        attempt = 0
        while attempt < tries:
            mbody = body
            if think:
                mbody = {**body, "generationConfig": {**body.get("generationConfig", {}), "thinkingConfig": {"thinkingLevel": "medium"}}}
            try:
                r = requests.post(url, json=mbody, headers={"x-goog-api-key": key}, timeout=45)
                if r.status_code == 200:
                    return r.json(), None, model
                if r.status_code not in (429, 503, 404):
                    try:
                        msg = r.json()["error"]["message"]
                    except Exception:
                        msg = r.text
                    msg = str(msg).replace(key, "[key removed]")[:200]
                    if r.status_code == 400 and think and "thinking" in msg.lower():
                        think = False       # same model, once more, without the thinking setting
                        continue
                    return None, f"Gemini unavailable (HTTP {r.status_code}): {msg}", None
                outcome = str(r.status_code)
                again = r.status_code != 404
            except requests.Timeout:
                outcome, again = "timeout", True
            except requests.ConnectionError:
                outcome, again = "connection error", True
            except Exception as e:
                return None, f"Gemini unavailable ({type(e).__name__})", None
            attempt += 1
            if not again or attempt >= tries:
                break
            time.sleep(2)
        failed.append((model, outcome))
    short = lambda m: m[len("gemini-"):] if m.startswith("gemini-") else m
    msg = "Gemini unavailable - " + ", ".join(f"{short(m)}: {o}" for m, o in failed) + "."
    if failed[-1][1] in ("429", "503", "timeout", "connection error"):
        msg += " Please try again in a moment."
    return None, msg, None

