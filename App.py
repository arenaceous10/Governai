def contradiction_hints(desc, answers, meta, scores):
    """One Gemini call that compares the answers with the final ratings. Advice only: it never changes a score, the tier
    or a reason. Returns (hints, note). Skips silently without a key or text answers; never raises."""
    key = secret("GEMINI_API_KEY")
    text = {q: a for q, a in answers.items() if str(a).strip() and a not in ("Yes", "No", "Not answered")}
    if not key or not text:
        return [], ""
    yn = {q: a for q, a in answers.items() if a in ("Yes", "No")}
    prompt = (
        "You are checking an AI risk assessment for conflicts. Below are the final risk ratings (1 = low, 3 = high) for nine "
        "dimensions, and the submitter's answers. Report ONLY a clear conflict between an answer and a rating, for example an "
        "answer that describes no human review while Automation is rated 1. Report at most 3. Each item is "
        "{\"dimension\": one of " + ", ".join(DIMS) + ", \"issue\": one plain sentence under 30 words}. "
        "Return an empty array [] if there is no clear conflict. Return only JSON.\n\n"
        f"Description: {desc}\nRatings: {json.dumps(scores)}\nYes/no answers: {json.dumps(yn)}\nText answers: {json.dumps(text)}")
    try:
        data_, err, _ = gemini_call(key, {"contents": [{"parts": [{"text": prompt}]}],
                                          "generationConfig": {"temperature": 0.2, "responseMimeType": "application/json"}}, max_models=2)
        if err:
            return [], "Hint check did not run."
        raw = data_["candidates"][0]["content"]["parts"][0]["text"]
        raw = raw[raw.find("["): raw.rfind("]") + 1]
        hints = []
        for h in json.loads(raw):
            if isinstance(h, dict) and h.get("dimension") in DIMS and str(h.get("issue", "")).strip():
                hints.append(dict(dimension=h["dimension"], issue=str(h["issue"]).strip()[:200]))
        return hints[:3], ""
    except Exception:
        return [], "Hint check did not run."

