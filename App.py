def queue_details(c, u):
    """What a reviewer is being asked to approve. Display only: nothing here feeds blockers(), approvers() or any rule."""
    risk, intake = json.loads(u["risk"]), json.loads(u["intake"])
    stage = u["stage"]
    done = {r["item"]: bool(r["done"]) for r in c.execute("select item, done from checklist where uc=? and stage=?", (u["id"], stage)).fetchall()}
    cond = c.execute("select stage, role, comment, at from approvals where uc=? and outcome='approved_with_conditions' order by stage, role", (u["id"],)).fetchall()
    acts = c.execute("select finding, action, owner, due from actions where uc=? and status='open' order by due", (u["id"],)).fetchall()
    return dict(purpose=str(intake.get("purpose") or "").strip(), owner=intake.get("model_owner") or "", bu=u["bu"],
                tier=TIER_LABEL.get(u["tier"], u["tier"]), score=risk.get("total"), reasons=list(risk.get("reasons") or []),
                stage=stage, stage_title=stage_title(stage), items=[(i, done.get(i, False)) for i in required_items(u)],
                evidence=list(STAGE_EVIDENCE.get(stage, [])), exit_gate=STAGE_EXIT_GATE.get(stage, ""),
                conditions=[dict(r) for r in cond], open_actions=[dict(r) for r in acts])

