def compliance_requirements(frameworks):
    return [r for fw in frameworks for r in COMPLIANCE_REQUIREMENTS.get(fw, [])]

def compliance_default_frameworks(u):
    """Frameworks already in the system's laws are ticked by default."""
    regs = set(json.loads(u["regs"]))
    return [fw for fw in COMPLIANCE_REQUIREMENTS if COMPLIANCE_ALIASES.get(fw, fw) in regs]

def compliance_question_count(tier, n_requirements):
    """About 2 questions per requirement for Medium and High systems, 1 for Low and Minimal, at most COMPLIANCE_CAP."""
    return min(COMPLIANCE_CAP, (2 if tier in ("medium", "high", "prohibited") else 1) * n_requirements)

def validate_compliance_questions(raw, valid_ids, cap=COMPLIANCE_CAP):
    """Strict. Each question must name exactly one known requirement_id and have text. Others are dropped and counted."""
    out, dropped = [], 0
    for item in raw if isinstance(raw, list) else []:
        rid = item.get("requirement_id") if isinstance(item, dict) else None
        q = str(item.get("q", "")).strip() if isinstance(item, dict) else ""
        if not isinstance(rid, str) or rid not in valid_ids or not q:
            dropped += 1
            continue
        if len(out) < cap:
            out.append(dict(requirement_id=rid, q=q[:300]))
    return out, dropped

def generate_compliance_questions(u, frameworks):
    """One Gemini call (through the shared fallback chain). Returns (questions, dropped, error). Changes nothing in the database."""
    key = secret("GEMINI_API_KEY")
    if not key:
        return [], 0, "No Gemini key set"
    reqs = compliance_requirements(frameworks)
    if not reqs:
        return [], 0, "Tick at least one framework."
    intake = json.loads(u["intake"])
    total = compliance_question_count(u["tier"], len(reqs))
    per = "2" if u["tier"] in ("medium", "high", "prohibited") else "1"
    prompt = (
        "You are helping check an AI system against indicative legal and framework requirements. Write specific, plain yes/no style "
        f"questions for this system. Write about {per} question per requirement and no more than {total} in total. Every question is "
        "tied to exactly one requirement_id from the list. Each must start with is, are, does, do, has, have, can or will and be answerable with Yes, Partly, No or Not applicable.\n\n"
        "Return ONLY a JSON array of {\"requirement_id\": \"...\", \"q\": \"question text\"}.\n\n"
        f"System name: {u['name']}\nDescription: {intake.get('purpose', '')}\nData types: {', '.join(intake.get('data', [])) or 'not stated'}\n"
        f"Degree of automation: {intake.get('automation', 'not stated')}\nRisk tier: {TIER_LABEL.get(u['tier'], u['tier'])}\n\nRequirements:\n"
        + "\n".join(f"- {r['id']} ({r['framework']}): {r['title']}. {r['summary']}" for r in reqs))
    data_, err, _ = gemini_call(key, {"contents": [{"parts": [{"text": prompt}]}],
                                      "generationConfig": {"temperature": 0.3, "responseMimeType": "application/json"}})
    if err:
        return [], 0, err
    try:
        raw = data_["candidates"][0]["content"]["parts"][0]["text"]
        raw = json.loads(raw[raw.find("["): raw.rfind("]") + 1])
    except Exception:
        return [], 0, "Gemini returned questions that could not be read. Please try again."
    qs, dropped = validate_compliance_questions(raw, {r["id"] for r in reqs}, total)
    if not qs:
        return [], dropped, "Gemini returned no usable compliance questions. Please try again."
    return qs, dropped, ""

def score_compliance(frameworks, questions, answers):
    """Fixed rules. Yes = 1, Partly = 0.5, No = 0; Not applicable and unanswered are left out. A requirement with several
    questions uses their average; a framework is the average over its requirements, as a percentage. A framework that was not
    ticked, or has no answered question, is 'not assessed' (never a misleading 0)."""
    reqmap = {r["id"]: r for r in compliance_requirements(COMPLIANCE_REQUIREMENTS)}
    out = {}
    for fw in COMPLIANCE_REQUIREMENTS:
        if fw not in frameworks:
            out[fw] = dict(status="not assessed", score=None, gaps=[], note="Not ticked for this check")
            continue
        per_req = {}
        for i, q in enumerate(questions):
            r = reqmap.get(q.get("requirement_id"))
            a = answers.get(str(i))
            if r and r["framework"] == fw and a in COMPLIANCE_POINTS:
                per_req.setdefault(r["id"], []).append(COMPLIANCE_POINTS[a])
        if not per_req:
            out[fw] = dict(status="not assessed", score=None, gaps=[], note="No answered questions")
            continue
        avg = {rid: sum(v) / len(v) for rid, v in per_req.items()}
        out[fw] = dict(status="scored", score=round(100 * sum(avg.values()) / len(avg)),
                       gaps=[dict(requirement_id=rid, title=reqmap[rid]["title"], score=round(s, 2)) for rid, s in avg.items() if s < 1],
                       note="")
    return out

def save_compliance_check(c, u, frameworks, questions, answers, notes, scores, actor):
    c.execute("insert into compliance_checks(uc,run_at,frameworks,qa,scores,actor) values(?,?,?,?,?,?)",
              (u["id"], now(), json.dumps(list(frameworks)), json.dumps(dict(questions=questions, answers=answers, notes=notes)),
               json.dumps(scores), actor))
    c.commit()
    done = [fw for fw, s in scores.items() if s["status"] == "scored"]
    log(actor, "compliance_checked", u["id"], "frameworks: " + ", ".join(frameworks) + "; scored: " + (", ".join(done) or "none"))

def compliance_runs(c, uid):
    return c.execute("select * from compliance_checks where uc=? order by id desc", (uid,)).fetchall()

def add_compliance_gap_actions(c, u, scores, actor):
    """Only when the user asks. One action per gap; the owner is left as Unassigned for the user to set."""
    have = {r["action"] for r in c.execute("select action from actions where uc=?", (u["id"],)).fetchall()}
    n = 0
    for fw, s in scores.items():
        for g in s.get("gaps", []):
            action = f"Close compliance gap ({fw}): {g['title']}"
            if action not in have:
                c.execute("insert into actions(uc,finding,action,owner,due,status,at) values(?,?,?,?,?,?,?)",
                          (u["id"], f"Compliance gap: {fw}", action, "Unassigned", (dt.date.today() + dt.timedelta(days=30)).isoformat(), "open", now()))
                n += 1
    c.commit()
    log(actor, "action_added", u["id"], f"{n} compliance gap action(s) added")
    return n

